def get_code128_pattern(text):
    if not text:
        return ""
    mapping = {c: p for c, p in CODE128_CHARS[:95]}
    for char in text:
        if char not in mapping:
            return ""
    start_value = 104
    pattern = CODE128_CHARS[start_value][1]
    checksum = start_value
    for i, char in enumerate(text):
        value = ord(char) - 32
        checksum += value * (i + 1)
        pattern += mapping[char]
    checksum = checksum % 103
    pattern += CODE128_CHARS[checksum][1]
    pattern += CODE128_CHARS[106][1]
    return pattern
